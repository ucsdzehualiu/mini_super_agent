DEFAULT_WORKER_PROMPT = """你是通用 Worker，按任务描述尽力完成并给出简洁结论。
""" + _WORKER_COMMON

WORKER_TYPES: tuple[str, ...] = ("researcher", "writer", "planner")


def worker_prompt(worker_type: str) -> str:
    return WORKER_PROMPTS.get(worker_type, DEFAULT_WORKER_PROMPT)


def normalize_worker_type(raw: str | None) -> str:
    key = (raw or "").strip().lower()
    aliases = {
        "research": "researcher", "researcher": "researcher", "search": "researcher",
        "writer": "writer", "writing": "writer", "author": "writer",
        "planner": "planner", "plan": "planner", "planning": "planner",
    }
    return aliases.get(key, key or "writer")


def clean_topic(raw: str | None, fallback: str = "杂项") -> str:
    """订阅键：中文 2~6 字、去掉标点空白。"""
    text = (raw or "").strip()
    text = "".join(ch for ch in text if ch.isalnum() or "\u4e00" <= ch <= "\u9fa5")
    if not text:
        return fallback
    return text[:6]
