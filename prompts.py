"""prompts.py —— 所有 system prompt。

这套 runtime 关心的是「系统怎么接管会话管理」，所以 Router 的 prompt 不是
「帮我把任务拆开」，而是「这条消息该交给谁、要不要打断现有的活」。四选一：

* ``direct``  —— 已经有人（某条任务）在管这件事，直接投递给它
* ``recall``  —— 是「刚才那个」的延续，顺着链召回已结束的任务接着做
* ``spawn``   —— 新事情，拆出一张或几张任务单
* ``ignore``  —— 不值得占用任何人的注意力

这个四选一的结果会直接打在 Console 的事件行上（直通/召回/拆单/忽略），
所以 prompt 的措辞要和 UI 上的词对齐。
"""

